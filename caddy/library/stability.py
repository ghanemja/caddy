"""The stability library: the principle caddy gives the model, and a lookup into real objects that behave like it.

The objects are NVIDIA SimReady assets (meshes, not CAD). They are never built or edited here. They serve as a
table of measured behaviour: for a friction value, what slope did real objects with that friction slide at? The
index is generated by tools/build_stability_library.py from ghanemja/behaviors (CC BY 4.0, see data/SOURCES.md).
"""
from __future__ import annotations

import json
import math
from functools import lru_cache
from pathlib import Path

import numpy as np

INDEX = Path(__file__).resolve().parents[2] / "data" / "library" / "stability_index.json"

PRINCIPLE = ("Stability in two lines. A rigid body on a slope SLIDES once the slope passes atan(μ), and TIPS once it "
             "passes atan(d / h): d is the distance from its centre of mass to the nearest support edge, h the height of "
             "the centre of mass. The smaller angle decides.")


@lru_cache(maxsize=1)
def index() -> dict:
    return json.loads(INDEX.read_text())


def card() -> dict:
    """The principle, its source and how far the slip half of it holds on the library."""
    ix = index()
    v = ix["validation"]
    return dict(principle=PRINCIPLE, source=ix["source"], n=v["n"],
                slip_check=f"measured slide angle vs atan(μ) on {v['n']} objects: correlation {v['corr_slide_vs_atan_mu']}, "
                           f"median error {v['median_abs_error_deg']}°",
                tip_check="not tested on library data (the library has no geometry); computed exactly per design")


def similar_friction(mu: float, k: int = 5, tol: float = 0.05) -> dict:
    """Library objects whose friction is nearest to `mu`: their measured slide angles and a few names."""
    rows = index()["assets"]
    mus = np.array([r[2] for r in rows])
    order = np.argsort(np.abs(mus - mu))
    near = [rows[i] for i in order[:max(k * 8, 40)] if abs(rows[i][2] - mu) <= tol] or [rows[i] for i in order[:k]]
    slides = np.array([r[3] for r in near])
    return dict(mu=round(mu, 3), slip_deg=round(math.degrees(math.atan(mu)), 1), n=len(near),
                library_median_slide_deg=round(float(np.median(slides)), 1),
                library_range_deg=[round(float(np.percentile(slides, 10)), 1), round(float(np.percentile(slides, 90)), 1)],
                examples=[dict(id=r[0], name=r[1], mu=r[2], slide_deg=r[3]) for r in near[:k]])
